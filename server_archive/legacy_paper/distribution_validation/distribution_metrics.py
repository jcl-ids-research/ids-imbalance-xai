# 2. KL Divergence & JS Divergence
# ============================================================================

def compute_kl_js_divergence(X_real: np.ndarray, X_synth: np.ndarray,
                              n_bins: int = 50, eps: float = 1e-10) -> Dict:
    """
    Compute per-feature KL and JS divergence.
    
    KL(P||Q): 0 = identical, higher = more different
    JS(P||Q): 0 to log(2) ≈ 0.693 (bounded, symmetric)
    """
    n_features = X_real.shape[1]
    kl_divs = []
    js_divs = []
    ks_stats = []
    ks_pvals = []

    for i in range(n_features):
        # Determine common bin range
        all_vals = np.concatenate([X_real[:, i], X_synth[:, i]])
        bins = np.linspace(np.min(all_vals), np.max(all_vals), n_bins)

        # Histograms
        p_real, _ = np.histogram(X_real[:, i], bins=bins, density=True)
        p_synth, _ = np.histogram(X_synth[:, i], bins=bins, density=True)

        # Add small epsilon to avoid log(0)
        p_real = p_real + eps
        p_synth = p_synth + eps
        p_real = p_real / p_real.sum()
        p_synth = p_synth / p_synth.sum()

        # KL divergence: KL(P_real || P_synth)
        kl = entropy(p_real, p_synth)

        # JS divergence: symmetric version
        m = 0.5 * (p_real + p_synth)
        js = 0.5 * entropy(p_real, m) + 0.5 * entropy(p_synth, m)

        kl_divs.append(kl)
        js_divs.append(js)

        # Kolmogorov-Smirnov test
        ks_stat, ks_p = ks_2samp(X_real[:, i], X_synth[:, i])
        ks_stats.append(ks_stat)
        ks_pvals.append(ks_p)

    # Summary statistics
    return {
        'kl_divergence': {
            'mean': float(np.mean(kl_divs)),
            'std': float(np.std(kl_divs)),
            'min': float(np.min(kl_divs)),
            'max': float(np.max(kl_divs)),
            'per_feature': [float(v) for v in kl_divs],
        },
        'js_divergence': {
            'mean': float(np.mean(js_divs)),
            'std': float(np.std(js_divs)),
            'min': float(np.min(js_divs)),
            'max': float(np.max(js_divs)),
            'per_feature': [float(v) for v in js_divs],
        },
        'ks_test': {
            'mean_stat': float(np.mean(ks_stats)),
            'mean_pvalue': float(np.mean(ks_pvals)),
            'features_reject_h0_5pct': int(np.sum(np.array(ks_pvals) < 0.05)),
            'n_features': n_features,
        }
    }



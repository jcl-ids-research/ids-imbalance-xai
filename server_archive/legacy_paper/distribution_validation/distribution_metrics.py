# 4. Correlation Matrix Distance
# ============================================================================

def compute_correlation_distance(X_real: np.ndarray, X_synth: np.ndarray) -> Dict:
    """
    Compare correlation structures between real and synthetic data.
    Measures how well pairwise feature correlations are preserved.
    """
    corr_real = np.corrcoef(X_real.T)
    corr_synth = np.corrcoef(X_synth.T)

    # Frobenius norm of difference
    corr_diff = corr_real - corr_synth
    frob_distance = np.linalg.norm(corr_diff, 'fro')

    # Mean absolute difference
    triu_idx = np.triu_indices_from(corr_real, k=1)
    mean_abs_diff = np.mean(np.abs(corr_diff[triu_idx]))
    max_abs_diff = np.max(np.abs(corr_diff[triu_idx]))

    return {
        'correlation_distance': {
            'frobenius_norm': float(frob_distance),
            'mean_abs_diff': float(mean_abs_diff),
            'max_abs_diff': float(max_abs_diff),
            'shape': corr_real.shape,
        }
    }



# 3. Wasserstein Distance (Earth Mover's Distance)
# ============================================================================

def compute_wasserstein_distance(X_real: np.ndarray, X_synth: np.ndarray) -> Dict:
    """Compute per-feature Wasserstein-1 distance."""
    n_features = X_real.shape[1]
    distances = []

    for i in range(n_features):
        wd = wasserstein_distance(X_real[:, i], X_synth[:, i])
        distances.append(wd)

    return {
        'wasserstein': {
            'mean': float(np.mean(distances)),
            'std': float(np.std(distances)),
            'min': float(np.min(distances)),
            'max': float(np.max(distances)),
            'per_feature': [float(v) for v in distances],
        }
    }



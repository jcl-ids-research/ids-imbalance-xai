# 1. Maximum Mean Discrepancy (MMD)
# ============================================================================

def rbf_kernel(X: torch.Tensor, Y: torch.Tensor, sigma: Optional[float] = None) -> torch.Tensor:
    """Compute RBF kernel matrix between X and Y."""
    X_norm = (X ** 2).sum(dim=1, keepdim=True)
    Y_norm = (Y ** 2).sum(dim=1, keepdim=True)
    dist = X_norm + Y_norm.T - 2.0 * torch.mm(X, Y.T)
    dist = torch.clamp(dist, min=0.0)

    if sigma is None:
        # Median heuristic for bandwidth
        with torch.no_grad():
            all_dist = dist.flatten()
            sigma = torch.sqrt(0.5 * torch.median(all_dist[all_dist > 0]))
            sigma = torch.clamp(sigma, min=1e-3)

    return torch.exp(-dist / (2.0 * sigma ** 2))


def compute_mmd(X: torch.Tensor, Y: torch.Tensor, sigma: Optional[float] = None) -> Dict:
    """
    Compute MMD^2 (biased estimator) and return with p-value approximation.
    
    Lower MMD = more similar distributions.
    MMD = 0 means identical distributions (in RKHS).
    """
    n, m = X.size(0), Y.size(0)

    K_xx = rbf_kernel(X, X, sigma)
    K_yy = rbf_kernel(Y, Y, sigma)
    K_xy = rbf_kernel(X, Y, sigma)

    # Biased MMD^2 estimator: ||E[phi(x)] - E[phi(y)]||^2
    mmd2 = (K_xx.sum() - K_xx.trace()) / (n * (n - 1)) + \
           (K_yy.sum() - K_yy.trace()) / (m * (m - 1)) - \
           2.0 * K_xy.mean()

    mmd = torch.sqrt(torch.clamp(mmd2, min=0.0))

    return {
        'mmd': mmd.item(),
        'mmd2': mmd2.item(),
        'sigma': sigma.item() if isinstance(sigma, torch.Tensor) else sigma,
    }


def compute_mmd_with_permutation(X: torch.Tensor, Y: torch.Tensor,
                                  n_permutations: int = 1000,
                                  sigma: Optional[float] = None) -> Dict:
    """
    Compute MMD with permutation test for p-value.
    p < 0.05 → distributions are significantly different.
    """
    result = compute_mmd(X, Y, sigma)
    mmd_obs = result['mmd']

    # Permutation test
    combined = torch.cat([X, Y], dim=0)
    n = X.size(0)
    mmd_perms = []

    for _ in range(n_permutations):
        idx = torch.randperm(combined.size(0))
        X_perm = combined[idx[:n]]
        Y_perm = combined[idx[n:]]
        perm_result = compute_mmd(X_perm, Y_perm, sigma)
        mmd_perms.append(perm_result['mmd'])

    mmd_perms = np.array(mmd_perms)
    p_value = (np.sum(mmd_perms >= mmd_obs) + 1) / (n_permutations + 1)

    result['p_value'] = p_value
    result['significant'] = p_value < 0.05
    result['permutation_threshold_95'] = np.percentile(mmd_perms, 95)

    return result



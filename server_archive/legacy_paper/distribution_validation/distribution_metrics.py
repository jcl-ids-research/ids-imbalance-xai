# 6. Principal Component Analysis
# ============================================================================

def compute_pca_metrics(X_real: np.ndarray, X_synth: np.ndarray,
                         n_components: int = 10) -> Dict:
    """
    Compare explained variance ratios and PCA projections.
    """
    # Fit PCA on real data, transform both
    pca = PCA(n_components=min(n_components, min(X_real.shape)))
    pca.fit(X_real)

    # Project both
    proj_real = pca.transform(X_real)
    proj_synth = pca.transform(X_synth)

    # Compare explained variance captured by synthetic data
    var_real = np.var(proj_real, axis=0)
    var_synth = np.var(proj_synth, axis=0)
    var_ratio = var_synth / (var_real + 1e-10)

    return {
        'pca': {
            'explained_variance_ratio': [float(v) for v in pca.explained_variance_ratio_],
            'cumulative_variance': float(np.cumsum(pca.explained_variance_ratio_)[n_components - 1]),
            'variance_ratio_real_vs_synth': [float(v) for v in var_ratio],
            'n_components_used': n_components,
        }
    }



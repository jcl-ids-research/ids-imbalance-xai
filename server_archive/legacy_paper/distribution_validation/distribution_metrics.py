def _generate_tsne_plot(X_real: np.ndarray, X_synth: np.ndarray,
                         output_dir: str, perplexity: int = 30):
    """Generate t-SNE comparison plot."""
    n_real = X_real.shape[0]
    combined = np.concatenate([X_real, X_synth], axis=0)

    # Subsample if too large
    max_samples = 5000
    if combined.shape[0] > max_samples:
        n_real_o = X_real.shape[0]
        n_synth = X_synth.shape[0]
        n_real_sub = min(n_real_o, max_samples // 2)
        n_synth_sub = min(n_synth, max_samples - n_real_sub)
        idx_real = np.random.choice(n_real_o, n_real_sub, replace=False)
        idx_synth = np.random.choice(n_synth, n_synth_sub, replace=False) + n_real_o
        idx = np.concatenate([idx_real, idx_synth])
        combined = combined[idx]
        labels = np.array(['Real'] * n_real_sub + ['Synth'] * n_synth_sub)
    else:
        labels = np.array(['Real'] * n_real + ['Synth'] * X_synth.shape[0])

    # PCA pre-reduction for t-SNE speed
    if combined.shape[1] > 50:
        pca = PCA(n_components=min(50, combined.shape[1]))
        combined = pca.fit_transform(combined)

    tsne = TSNE(n_components=2, perplexity=min(perplexity, combined.shape[0] - 1),
                random_state=42, n_iter=1000)
    emb = tsne.fit_transform(combined)

    fig, ax = plt.subplots(1, 1, figsize=(10, 8))
    colors = {'Real': '#2196F3', 'Synth': '#FF5722'}
    for label in ['Real', 'Synth']:
        mask = labels == label
        ax.scatter(emb[mask, 0], emb[mask, 1], c=colors[label], label=label,
                   alpha=0.6, s=10)
    ax.set_title('t-SNE: Real vs Synthetic Samples', fontsize=14)
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, 'tsne_comparison.png'), dpi=150)
    plt.close()
    print(f"  [Plot] t-SNE saved to {output_dir}/tsne_comparison.png")


def _generate_pca_plot(X_real: np.ndarray, X_synth: np.ndarray,
                        output_dir: str):
    """Generate PCA comparison plot (2D projection)."""
    pca = PCA(n_components=2)
    combined = np.concatenate([X_real, X_synth], axis=0)
    proj = pca.fit_transform(combined)

    n_real = X_real.shape[0]
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))

    # PCA projection
    axes[0].scatter(proj[:n_real, 0], proj[:n_real, 1], c='#2196F3',
                    label='Real', alpha=0.5, s=8)
    axes[0].scatter(proj[n_real:, 0], proj[n_real:, 1], c='#FF5722',
                    label='Synthetic', alpha=0.5, s=8)
    axes[0].set_xlabel(f'PC1 ({pca.explained_variance_ratio_[0]:.1%})')
    axes[0].set_ylabel(f'PC2 ({pca.explained_variance_ratio_[1]:.1%})')
    axes[0].set_title('PCA Projection')
    axes[0].legend()
    axes[0].grid(True, alpha=0.3)

    # Explained variance
    n_plot = min(20, len(pca.explained_variance_ratio_))
    axes[1].bar(range(n_plot), pca.explained_variance_ratio_[:n_plot],
                color='#4CAF50', alpha=0.7)
    axes[1].plot(range(n_plot), np.cumsum(pca.explained_variance_ratio_)[:n_plot],
                 'r-o', markersize=4)
    axes[1].axhline(0.95, color='gray', linestyle='--', alpha=0.5)
    axes[1].set_xlabel('Principal Component')
    axes[1].set_ylabel('Explained Variance Ratio')
    axes[1].set_title('PCA Explained Variance')
    axes[1].grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, 'pca_comparison.png'), dpi=150)
    plt.close()
    print(f"  [Plot] PCA saved to {output_dir}/pca_comparison.png")


def _generate_feature_histograms(X_real: np.ndarray, X_synth: np.ndarray,
                                  feature_names: List[str], output_dir: str,
                                  max_features: int = 16):
    """Generate per-feature histogram comparison."""
    n_features = X_real.shape[1]
    n_plot = min(max_features, n_features)
    n_cols = 4
    n_rows = (n_plot + n_cols - 1) // n_cols

    fig, axes = plt.subplots(n_rows, n_cols, figsize=(n_cols * 4, n_rows * 3))
    axes = axes.flatten()

    for i in range(n_plot):
        ax = axes[i]
        ax.hist(X_real[:, i], bins=50, alpha=0.6, color='#2196F3',
                label='Real', density=True)
        ax.hist(X_synth[:, i], bins=50, alpha=0.6, color='#FF5722',
                label='Synthetic', density=True)
        ax.set_title(feature_names[i] if i < len(feature_names) else f'F{i}')
        ax.legend(fontsize=6)
        ax.grid(True, alpha=0.2)

    # Hide empty subplots
    for i in range(n_plot, len(axes)):
        axes[i].set_visible(False)

    plt.suptitle('Feature-wise Distribution Comparison', fontsize=14)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, 'feature_histograms.png'), dpi=150)
    plt.close()
    print(f"  [Plot] Feature histograms saved to {output_dir}/feature_histograms.png")


def _generate_correlation_plots(X_real: np.ndarray, X_synth: np.ndarray,
                                 feature_names: List[str], output_dir: str):
    """Generate correlation matrix comparison."""
    corr_real = np.corrcoef(X_real.T)
    corr_synth = np.corrcoef(X_synth.T)
    corr_diff = np.abs(corr_real - corr_synth)

    fig, axes = plt.subplots(1, 3, figsize=(18, 6))

    vmin, vmax = -1, 1
    sns.heatmap(corr_real, ax=axes[0], cmap='RdBu_r', vmin=vmin, vmax=vmax,
                xticklabels=False, yticklabels=False, cbar_kws={'label': 'Correlation'})
    axes[0].set_title('Real Data Correlation')

    sns.heatmap(corr_synth, ax=axes[1], cmap='RdBu_r', vmin=vmin, vmax=vmax,
                xticklabels=False, yticklabels=False, cbar_kws={'label': 'Correlation'})
    axes[1].set_title('Synthetic Data Correlation')

    sns.heatmap(corr_diff, ax=axes[2], cmap='YlOrRd',
                xticklabels=False, yticklabels=False, cbar_kws={'label': '|Diff|'})
    axes[2].set_title('Absolute Difference')

    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, 'correlation_comparison.png'), dpi=150)
    plt.close()
    print(f"  [Plot] Correlation matrices saved to {output_dir}/correlation_comparison.png")


def _generate_summary_radar(results: Dict, output_dir: str):
    """Generate radar chart summarizing all metrics."""
    metrics = {
        'MMD\n(lower=better)': 1.0 - min(results.get('mmd', {}).get('mmd', 0) * 10, 1.0),
        'JS Div.\n(lower=better)': 1.0 - min(results.get('divergence', {}).get('js_divergence', {}).get('mean', 0) * 5, 1.0),
        'KL Div.\n(lower=better)': 1.0 - min(results.get('divergence', {}).get('kl_divergence', {}).get('mean', 0) * 2, 1.0),
        'Correlation\n(higher=better)': 1.0 - min(results.get('correlation', {}).get('correlation_distance', {}).get('mean_abs_diff', 0) * 5, 1.0),
        'Coverage\n(higher=better)': results.get('coverage', {}).get('coverage', {}).get('density', 0),
    }

    labels = list(metrics.keys())
    values = list(metrics.values())
    N = len(labels)
    angles = [n / float(N) * 2 * np.pi for n in range(N)]
    values += values[:1]
    angles += angles[:1]

    fig, ax = plt.subplots(figsize=(8, 8), subplot_kw=dict(polar=True))
    ax.plot(angles, values, 'o-', linewidth=2, color='#2196F3')
    ax.fill(angles, values, alpha=0.25, color='#2196F3')
    ax.set_xticks(angles[:-1])
    ax.set_xticklabels(labels, fontsize=10)
    ax.set_ylim(0, 1)
    ax.set_title('Synthetic Sample Quality Summary', fontsize=14, pad=20)
    ax.grid(True)

    # Add score

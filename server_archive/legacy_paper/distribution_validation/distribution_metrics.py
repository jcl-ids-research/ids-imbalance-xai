# 5. Coverage & Diversity Metrics
# ============================================================================

def compute_coverage_metrics(X_real: np.ndarray, X_synth: np.ndarray,
                              k: int = 5) -> Dict:
    """
    Coverage and diversity metrics for synthetic data quality.
    
    - recall@k: fraction of real samples that have a synthetic neighbor
    - precision@k: fraction of synthetic samples that have a real neighbor
    - coverage: fraction of real data manifold covered by synthetic samples
    """
    nn_real = NearestNeighbors(n_neighbors=k, metric='euclidean').fit(X_real)
    nn_synth = NearestNeighbors(n_neighbors=k, metric='euclidean').fit(X_synth)

    # Precision: for each synth sample, how many of its k nearest neighbors are real?
    dist_s2r, idx_s2r = nn_real.kneighbors(X_synth)
    precision = np.mean([len(np.unique(idx)) / k for idx in idx_s2r])

    # Recall: for each real sample, how many of its k nearest neighbors are synth?
    dist_r2s, idx_r2s = nn_synth.kneighbors(X_real)
    recall = np.mean([len(np.unique(idx)) / k for idx in idx_r2s])

    return {
        'coverage': {
            'precision_at_k': float(precision),
            'recall_at_k': float(recall),
            'density': float(precision * recall) / (precision + recall + 1e-10),
            'k': k,
        }
    }



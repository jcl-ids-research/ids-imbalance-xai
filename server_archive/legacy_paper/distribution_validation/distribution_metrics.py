    """
    Run all distribution validation metrics and generate plots.
    
    Args:
        X_real:   Real training samples (n_real, n_features)
        X_synth:  Synthetic samples (n_synth, n_features)
        feature_names: Optional feature names for plots
        output_dir: Output directory for results and plots
        n_permutations: Number of permutations for MMD test
        n_bins: Number of bins for KL/JS divergence
        use_tsne: Whether to generate t-SNE plot
    
    Returns:
        Dictionary with all metrics
    """
    os.makedirs(output_dir, exist_ok=True)
    
    if feature_names is None:
        feature_names = [f'F{i}' for i in range(X_real.shape[1])]

    print("=" * 60)
    print("Distribution Validation - Full Report")
    print(f"Real samples:    {X_real.shape}")
    print(f"Synth samples:   {X_synth.shape}")
    print(f"Features:        {X_real.shape[1]}")
    print("=" * 60)

    # Convert to torch for MMD
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    X_real_t = torch.FloatTensor(X_real).to(device)
    X_synth_t = torch.FloatTensor(X_synth).to(device)

    results = {}

    # 1. MMD
    print("\n[1/6] Computing MMD with permutation test...")
    mmd_result = compute_mmd_with_permutation(X_real_t, X_synth_t, n_permutations)
    results['mmd'] = mmd_result
    print(f"  MMD = {mmd_result['mmd']:.6f} "
          f"(p = {mmd_result['p_value']:.4f}, "
          f"{'SIGNIFICANT' if mmd_result['significant'] else 'NOT significant'})")

    # 2. KL & JS Divergence
    print("\n[2/6] Computing KL/JS divergence and KS tests...")
    div_result = compute_kl_js_divergence(X_real, X_synth, n_bins)
    results['divergence'] = div_result
    print(f"  KL mean: {div_result['kl_divergence']['mean']:.6f}")
    print(f"  JS mean: {div_result['js_divergence']['mean']:.6f}")
    print(f"  KS reject@5%: {div_result['ks_test']['features_reject_h0_5pct']}/"
          f"{div_result['ks_test']['n_features']} features")

    # 3. Wasserstein Distance
    print("\n[3/6] Computing Wasserstein distance...")
    wasser_result = compute_wasserstein_distance(X_real, X_synth)
    results['wasserstein'] = wasser_result
    print(f"  Wasserstein mean: {wasser_result['wasserstein']['mean']:.6f}")

    # 4. Correlation Distance
    print("\n[4/6] Computing correlation structure preservation...")
    corr_result = compute_correlation_distance(X_real, X_synth)
    results['correlation'] = corr_result
    print(f"  Frobenius norm: {corr_result['correlation_distance']['frobenius_norm']:.4f}")
    print(f"  Mean abs diff:  {corr_result['correlation_distance']['mean_abs_diff']:.4f}")

    # 5. Coverage
    print("\n[5/6] Computing coverage metrics (precision/recall@k)...")
    cov_result = compute_coverage_metrics(X_real, X_synth)
    results['coverage'] = cov_result
    print(f"  Precision@k: {cov_result['coverage']['precision_at_k']:.4f}")
    print(f"  Recall@k:    {cov_result['coverage']['recall_at_k']:.4f}")

    # 6. PCA
    print("\n[6/6] Computing PCA analysis...")
    pca_result = compute_pca_metrics(X_real, X_synth)
    results['pca'] = pca_result

    # --- Generate Plots ---
    print("\nGenerating plots...")

    # t-SNE visualization
    if use_tsne:
        _generate_tsne_plot(X_real, X_synth, output_dir)

    # PCA visualization
    _generate_pca_plot(X_real, X_synth, output_dir)

    # Feature-wise histogram comparison (sample up to 16 features)
    _generate_feature_histograms(X_real, X_synth, feature_names, output_dir)

    # Correlation matrix comparison
    _generate_correlation_plots(X_real, X_synth, feature_names, output_dir)

